/// Frame 13 - detailed breakdown of the recommended combination.
///
/// When an [outfit] generated by the backend is supplied, the piece grid,
/// score ring and factor bars render its live compatibility report
/// (`POST /ai/calculate-compatibility`). Without an outfit the screen shows an
/// empty state; it never falls back to bundled demo values.
class PerfectMatchScreen extends StatefulWidget {
  PerfectMatchScreen._({
    this.outfit,
    WardrobeController? wardrobeController,
    OutfitsController? outfitsController,
  })  : _wardrobeController = wardrobeController ?? AppState.instance.wardrobeController,
        _outfitsController = outfitsController ?? AppState.instance.outfitsController;

  factory PerfectMatchScreen({
    Key? key,
    Outfit? outfit,
    WardrobeController? wardrobeController,
    OutfitsController? outfitsController,
  }) {
    return PerfectMatchScreen._(
      outfit: outfit,
      wardrobeController: wardrobeController,
      outfitsController: outfitsController,
    );
  }

  final Outfit? outfit;
  final WardrobeController _wardrobeController;
  final OutfitsController _outfitsController;

  @override
  State<PerfectMatchScreen> createState() => _PerfectMatchScreenState();
}

class _PerfectMatchScreenState extends State<PerfectMatchScreen> {
  List<MatchFactor>? _factors;
  List<ClothingItem>? _pieces;

  @override
  void initState() {
    super.initState();
    _resolve();
  }

  Future<void> _resolve() async {
    final outfit = widget.outfit;
    if (outfit == null) return;
    // Resolve piece images from the live wardrobe.
    final ids = outfit.itemIds ?? const <String>[];
    if (ids.isNotEmpty) {
      if (widget._wardrobeController.items.isEmpty) {
        await widget._wardrobeController.load();
      }
      final wardrobe = widget._wardrobeController.items;
      final found = [
        for (final id in ids)
          ...wardrobe.where((w) => w.id == id),
      ];
      if (found.isNotEmpty && mounted) setState(() => _pieces = found);
    }
    // Prefer the weights the engine reported with the outfit; only call the
    // compatibility endpoint when the outfit arrived without a breakdown.
    if (outfit.factors != null && outfit.factors!.isNotEmpty) {
      if (mounted) setState(() => _factors = outfit.factors);
      return;
    }
    if (outfit.breakdown != null && outfit.breakdown!.isNotEmpty) {
      if (mounted) {
        setState(() => _factors = [
          for (final row in outfit.breakdown!)
            MatchFactor(label: row.label, value: row.value),
        ]);
      }
      return;
    }
    if (ids.length >= 2) {
      final compat = await widget._outfitsController.compatibility(ids);
      if (!mounted) return;
      final rows = (compat?['breakdown'] as List?) ?? [];
      if (rows.isNotEmpty) {
        setState(() {
          _factors = [
            for (final b in rows)
              if (b is Map)
                matchFactorFromJson(Map<String, dynamic>.from(b)),
          ];
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final outfit = widget.outfit;
    if (outfit == null) {
      return SwScreen(
        child: Column(
          children: [
            const SwAppBar(title: 'Perfect Match'),
            Expanded(
              child: Center(
                child: Padding(
                  padding: const EdgeInsets.all(Insets.xl),
                  child: Text(
                    'Open an outfit to see its compatibility breakdown.',
                    textAlign: TextAlign.center,
                    style: AppText.caption,
                  ),
                ),
              ),
            ),
          ],
        ),
      );
    }

    final breakdown = _factors ?? outfit.factors ?? const <MatchFactor>[];
    // Factors the engine had no evidence for are dropped and renormalised
    // away; showing them as ordinary scores would overstate the confidence.
    final applied = breakdown.where((f) => f.applied).toList();
    final skipped = breakdown.where((f) => !f.applied).toList();
    final pieces = _pieces ?? const <ClothingItem>[];
    final images = pieces.isNotEmpty
        ? [for (final p in pieces) p.image]
        : (outfit.image.trim().isEmpty ? const <String>[] : [outfit.image]);
    final match = outfit.match;
    final why = outfit.explanation ??
        'This look is built from items already in your wardrobe.';

    return SwScreen(
      scroll: true,
      padding: const EdgeInsets.only(bottom: Insets.xxl),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const SwAppBar(title: 'Perfect Match'),
          Padding(
            padding: const EdgeInsets.symmetric(horizontal: Insets.gutter),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                SwCard(
                  padding: const EdgeInsets.all(Insets.lg),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        "TODAY'S FLATLAY SUGGESTION",
                        style: AppText.overline,
                      ),
                      const SizedBox(height: Insets.md),
                      _PieceGrid(images: images),
                    ],
                  ),
                ),
                const SizedBox(height: Insets.lg),
                _ScoreCard(match: match),
                const SizedBox(height: Insets.xl),
                Row(
                  children: [
                    Expanded(
                      child: Text('AI Breakdown Analysis', style: AppText.h4),
                    ),
                    if (applied.length < breakdown.length)
                      Text(
                        '${applied.length}/${breakdown.length} scored',
                        style: AppText.caption,
                      ),
                  ],
                ),
                const SizedBox(height: Insets.md),
                SwCard(
                  padding: const EdgeInsets.symmetric(
                    horizontal: Insets.lg,
                    vertical: Insets.lg,
                  ),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      if (applied.isEmpty)
                        Text(
                          'No factor breakdown is available for this outfit yet.',
                          style: AppText.caption,
                        )
                      else
                        for (var i = 0; i < applied.length; i++) ...[
                          _ScoreBar(
                            label: applied[i].label,
                            value: applied[i].value,
                            weight: applied[i].weight,
                          ),
                          if (i != applied.length - 1)
                            const SizedBox(height: Insets.lg),
                        ],
                      if (skipped.isNotEmpty) ...[
                        const SizedBox(height: Insets.lg),
                        Text(
                          'Not scored yet — these need more signal from you:',
                          style: AppText.caption,
                        ),
                        const SizedBox(height: Insets.sm),
                        Wrap(
                          spacing: 6,
                          runSpacing: 6,
                          children: [
                            for (final f in skipped)
                              Text(
                                f.label,
                                style: AppText.caption.copyWith(
                                  color: AppColors.textTertiary,
                                ),
                              ),
                          ],
                        ),
                      ],
                    ],
                  ),
                ),
                const SizedBox(height: Insets.lg),
                SwBanner(
                  icon: SwIcon.sparkle,
                  title: 'WHY THIS OUTFIT?',
                  message: why,
                ),
                const SizedBox(height: Insets.xl),
                ListenableBuilder(
                  listenable: widget._outfitsController,
                  builder: (context, _) {
                    final saved = widget._outfitsController.findSaved(outfit);
                    final isSaved = saved != null;
                    final isFav = saved?.favorite ?? false;
                    Future<void> run(Future<bool?> Function() action,
                        String on, String off) async {
                      final r = await action();
                      if (!context.mounted) return;
                      ScaffoldMessenger.of(context)
                        ..hideCurrentSnackBar()
                        ..showSnackBar(SnackBar(
                          content: Text(r == null
                              ? 'Could not update this outfit. Check the backend and try again.'
                              : (r ? on : off)),
                        ));
                    }

                    final ids = outfit.itemIds ?? const <String>[];
                    return Column(
                      children: [
                        SwOutlineButton(
                          label: isSaved ? 'Saved \u2605 (tap to remove)' : 'Save Outfit \u2606',
                          foreground:
                              isSaved ? AppColors.primary : AppColors.textPrimary,
                          onTap: ids.isEmpty
                              ? null
                              : () => run(
                                    () => widget._outfitsController.toggleSaved(
                                      name: outfit.name,
                                      itemIds: ids,
                                      occasion: outfit.occasion,
                                    ),
                                    'Outfit saved.',
                                    'Removed from Saved.',
                                  ),
                        ),
                        const SizedBox(height: Insets.md),
                        SwOutlineButton(
                          label: isFav ? 'Favorite \u2665' : 'Add to Favorites \u2661',
                          foreground:
                              isFav ? AppColors.primary : AppColors.textPrimary,
                          onTap: ids.isEmpty
                              ? null
                              : () => run(
                                    () => widget._outfitsController
                                        .toggleFavoriteFor(
                                      name: outfit.name,
                                      itemIds: ids,
                                      occasion: outfit.occasion,
                                    ),
                                    'Added to Favorites.',
                                    'Removed from Favorites.',
                                  ),
                        ),
                      ],
                    );
                  },
                ),
                const SizedBox(height: Insets.md),
                SwOutlineButton(
                  label: 'Preview on Avatar',
                  onTap: () => Navigator.of(context).pushNamed(Routes.styleAvatar),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}

/// Two by two grid of the garments in the recommendation.
class _PieceGrid extends StatelessWidget {
  const _PieceGrid({required this.images});

  final List<String> images;

  @override
  Widget build(BuildContext context) {
    return GridView.builder(
      shrinkWrap: true,
      physics: const NeverScrollableScrollPhysics(),
      itemCount: images.length,
      gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
        crossAxisCount: 2,
        mainAxisSpacing: Insets.md,
        crossAxisSpacing: Insets.md,
        childAspectRatio: 1.05,
      ),
      itemBuilder: (context, i) {
        return SwProductImage(image: images[i], radius: Radii.md);
      },
    );
  }
}

/// Ring gauge plus the confidence copy.
class _ScoreCard extends StatelessWidget {
  const _ScoreCard({required this.match});

  final int match;

  @override
  Widget build(BuildContext context) {
    return SwCard(
      padding: const EdgeInsets.all(Insets.lg),
      child: Row(
        children: [
          SizedBox.square(
            dimension: 72,
            child: CustomPaint(
              painter: _RingPainter(match / 100),
              child: Center(
                child: Text(
                  '$match%',
                  style: AppText.numeric.copyWith(fontSize: 18),
                ),
              ),
            ),
          ),
          const SizedBox(width: Insets.lg),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text('Compatibility Score', style: AppText.cardTitle),
                const SizedBox(height: 4),
                Text(
                  'Weighted across colour, style, occasion and your saved '
                  'preferences.',
                  style: AppText.caption,
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}

/// Circular progress ring used for the compatibility score.
class _RingPainter extends CustomPainter {
  const _RingPainter(this.value);

  final double value;

  @override
  void paint(Canvas canvas, Size size) {
    const stroke = 6.0;
    final rect = Offset.zero & size;

    canvas.drawArc(
      rect.deflate(stroke / 2),
      0,
      6.28318,
      false,
      Paint()
        ..style = PaintingStyle.stroke
        ..strokeWidth = stroke
        ..color = AppColors.border,
    );
    canvas.drawArc(
      rect.deflate(stroke / 2),
      -1.5708,
      6.28318 * value,
      false,
      Paint()
        ..style = PaintingStyle.stroke
        ..strokeWidth = stroke
        ..strokeCap = StrokeCap.round
        ..color = AppColors.primary,
    );
  }

  @override
  bool shouldRepaint(_RingPainter old) => old.value != value;
}

class _ScoreBar extends StatelessWidget {
  const _ScoreBar({
    required this.label,
    required this.value,
    this.weight = 0,
  });

  final String label;
  final int value;

  /// Share of the total score this factor carried, 0..1. Shown when the
  /// engine reported weights so the user can see what actually moved the
  /// number rather than treating all factors as equal.
  final double weight;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          children: [
            Expanded(child: Text(label, style: AppText.body)),
            if (weight > 0)
              Padding(
                padding: const EdgeInsets.only(right: 6),
                child: Text(
                  '${(weight * 100).round()}% wt',
                  style: AppText.caption.copyWith(fontSize: 10),
                ),
              ),
            Text('$value%', style: AppText.bodyStrong.copyWith(fontSize: 13)),
          ],
        ),
        const SizedBox(height: 6),
        ClipRRect(
          borderRadius: Radii.pillRadius,
          child: LinearProgressIndicator(
            value: value / 100,
            minHeight: 5,
            backgroundColor: AppColors.border,
            valueColor: const AlwaysStoppedAnimation(AppColors.primary),
          ),
        ),
      ],
    );
  }
}
